#include <Arduino.h>
#include "kymo_config.h"

static KymoContext kymo;

/*******************************************************************************
 * setup
 ******************************************************************************/
void setup() {
    Serial.begin(115200);
    (void)Kymo_Init(&kymo, &kymo_config);
}

/*******************************************************************************
 * loop
 ******************************************************************************/
void loop() {
    (void)Kymo_Main(&kymo);
}
